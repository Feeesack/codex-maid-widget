'use strict';

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const catalog = require('../src/interaction-sound-catalog.js');

const ROOT = path.resolve(__dirname, '..');
// Separately bundled encoded presets are not regenerated from the PCM WAV bank.
const PUBLIC_PRESETS = Object.freeze(catalog.presets.filter(preset => !preset.separateBank));
// Deliberately fixed inputs/outputs: never scan or embed arbitrary asset files.
const ROLES = Object.freeze(['press', 'release']);
const OUTPUTS = Object.freeze([
  'src/interaction-samples.js',
  'macos/src/interaction-samples.js',
]);

function readPcmWav(file) {
  const audio = fs.readFileSync(file);
  if (audio.length < 44 || audio.toString('ascii', 0, 4) !== 'RIFF'
    || audio.toString('ascii', 8, 12) !== 'WAVE'
    || audio.readUInt32LE(4) !== audio.length - 8) {
    throw new Error(`Invalid interaction WAV: ${file}`);
  }
  let format = null;
  let dataLength = null;
  let offset = 12;
  while (offset + 8 <= audio.length) {
    const id = audio.toString('ascii', offset, offset + 4);
    const length = audio.readUInt32LE(offset + 4);
    const start = offset + 8;
    if (start + length > audio.length) throw new Error(`Truncated interaction WAV: ${file}`);
    if (id === 'fmt ') {
      if (length < 16 || format) throw new Error(`Invalid WAV format chunk: ${file}`);
      format = {
        encoding: audio.readUInt16LE(start),
        channels: audio.readUInt16LE(start + 2),
        sampleRate: audio.readUInt32LE(start + 4),
        byteRate: audio.readUInt32LE(start + 8),
        blockAlign: audio.readUInt16LE(start + 12),
        bits: audio.readUInt16LE(start + 14),
      };
    }
    if (id === 'data') {
      if (dataLength !== null) throw new Error(`Duplicate WAV data chunk: ${file}`);
      dataLength = length;
    }
    offset = start + length + (length % 2);
  }
  if (offset !== audio.length || !format || dataLength === null
    || format.encoding !== 1 || format.channels !== 1
    || format.sampleRate !== 44100 || format.bits !== 16
    || format.blockAlign !== 2 || format.byteRate !== 88200
    || dataLength % 2 !== 0) {
    throw new Error(`Expected 44.1 kHz mono 16-bit PCM interaction WAV: ${file}`);
  }
  const durationMs = dataLength / format.byteRate * 1000;
  if (durationMs < 50 || durationMs > 220) {
    throw new Error(`Expected interaction WAV duration between 50 and 220 ms: ${file}`);
  }
  return audio;
}

function renderModule(presets) {
  return [
    '// Generated by scripts/prepare-interaction-audio.cjs; do not edit.',
    '// Sources, processing and licenses: see assets/audio/manifest.json.',
    '(function (root, factory) {',
    "  'use strict';",
    '  const samples = factory();',
    "  if (typeof module === 'object' && module.exports) module.exports = samples;",
    '  else root.MaidInteractionSamples = samples;',
    "})(typeof globalThis !== 'undefined' ? globalThis : this, function () {",
    "  'use strict';",
    '  const presets = Object.freeze({',
    ...PUBLIC_PRESETS.map(({ id }) => `    ${JSON.stringify(id)}: Object.freeze(${JSON.stringify(presets[id])}),`),
    '  });',
    '  return Object.freeze({',
    `    defaultId: ${JSON.stringify(catalog.defaultId)},`,
    '    presets,',
    `    press: presets[${JSON.stringify(catalog.defaultId)}].press,`,
    `    release: presets[${JSON.stringify(catalog.defaultId)}].release,`,
    '  });',
    '});',
    '',
  ].join('\n');
}

function pcmWav(samples) {
  const wav = Buffer.alloc(44 + samples.length * 2);
  wav.write('RIFF', 0); wav.writeUInt32LE(wav.length - 8, 4); wav.write('WAVEfmt ', 8);
  wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22);
  wav.writeUInt32LE(44100, 24); wav.writeUInt32LE(88200, 28);
  wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34); wav.write('data', 36);
  wav.writeUInt32LE(samples.length * 2, 40);
  for (let n = 0; n < samples.length; n++) wav.writeInt16LE(Math.round(samples[n] * 32767), 44 + n * 2);
  return wav;
}

// Reproduce v0.3.33's Web Audio oscillator analytically, preserving its frequency,
// phase, amplitude and exponential gain ramps. A 40 ms complementary overlap
// separates the original gesture at 10–50 ms without duplicating the whole chirp.
// Only the last 5 ms receive an extra fade to silence to avoid a PCM boundary click.
function synthesizeOriginalClips() {
  const rate = 44100, length = Math.round(.22 * rate);
  const chirp = new Float64Array(length), press = new Float64Array(Math.round(.05 * rate));
  const releaseStart = Math.round(.01 * rate), release = new Float64Array(length - releaseStart);
  const ramp = Math.log(1050 / 730) / .1;
  const rampCycles = 730 * Math.expm1(ramp * .1) / ramp;
  for (let n = 0; n < length; n++) {
    const t = n / rate;
    const cycles = t <= .1 ? 730 * Math.expm1(ramp * t) / ramp : rampCycles + 1050 * (t - .1);
    const gain = t <= .012 ? .001 * Math.pow(180, t / .012)
      : t <= .2 ? .18 * Math.pow(.001 / .18, (t - .012) / .188) : .001;
    const tail = t < .215 ? 1 : Math.pow(Math.cos(Math.PI / 2 * (n - .215 * rate) / (length - 1 - .215 * rate)), 2);
    chirp[n] = Math.sin(2 * Math.PI * cycles) * gain * tail;
  }
  for (let n = 0; n < press.length; n++) {
    const mix = n < releaseStart ? 1 : Math.pow(Math.cos(Math.PI / 2 * (n - releaseStart) / (press.length - 1 - releaseStart)), 2);
    press[n] = chirp[n] * mix;
  }
  for (let n = 0; n < release.length; n++) {
    const originalIndex = n + releaseStart;
    const mix = originalIndex >= press.length ? 1 : Math.pow(Math.sin(Math.PI / 2 * n / (press.length - 1 - releaseStart)), 2);
    release[n] = chirp[originalIndex] * mix;
  }
  return { press: pcmWav(press), release: pcmWav(release), reference: pcmWav(chirp), overlapMs: 40 };
}

function prepareInteractionAudio({ check = false } = {}) {
  const manifestPath = path.join(ROOT, 'assets', 'audio', 'manifest.json');
  const manifestBytes = fs.readFileSync(manifestPath);
  if (!manifestBytes.equals(fs.readFileSync(path.join(ROOT, 'macos', 'assets', 'audio', 'manifest.json')))) {
    throw new Error('Interaction audio manifest mirror differs');
  }
  const manifest = JSON.parse(manifestBytes.toString('utf8'));
  const publicIds = PUBLIC_PRESETS.map(preset => preset.id);
  if (!publicIds.includes(catalog.defaultId) || manifest.defaultId !== catalog.defaultId
    || manifest.presets.length !== publicIds.length
    || manifest.presets.some((preset, index) => preset.id !== publicIds[index])) {
    throw new Error('Interaction audio manifest/catalog mismatch');
  }
  const catalogBytes = fs.readFileSync(path.join(ROOT, 'src', 'interaction-sound-catalog.js'));
  if (!catalogBytes.equals(fs.readFileSync(path.join(ROOT, 'macos', 'src', 'interaction-sound-catalog.js')))) {
    throw new Error('Interaction sound catalog mirror differs');
  }
  const presets = {}, generatedOriginal = synthesizeOriginalClips();
  for (const { id } of PUBLIC_PRESETS) {
    const entry = manifest.presets.find(preset => preset.id === id);
    if (!entry || !Number.isFinite(entry.gain) || entry.gain <= 0 || entry.gain > 1) {
      throw new Error(`Invalid interaction audio preset: ${id}`);
    }
    const samples = { gain: entry.gain };
    for (const role of ROLES) {
      const clip = entry.clips[role], file = clip?.file;
      if (typeof file !== 'string' || !/^[a-z0-9-]+\.wav$/.test(file)) throw new Error(`Invalid interaction filename: ${id}/${role}`);
      const source = path.join(ROOT, 'assets', 'audio', file);
      const mirror = path.join(ROOT, 'macos', 'assets', 'audio', file);
      const audio = readPcmWav(source);
      if (!audio.equals(readPcmWav(mirror))) throw new Error(`Interaction WAV mirror differs: ${file}`);
      if (crypto.createHash('sha256').update(audio).digest('hex') !== clip.sha256) throw new Error(`Interaction WAV hash differs: ${file}`);
      if (id === 'original' && !audio.equals(generatedOriginal[role])) throw new Error(`Original chirp reproduction differs: ${role}`);
      // Plain base64 avoids fetch under the renderer's connect-src CSP policy.
      samples[role] = audio.toString('base64');
    }
    presets[id] = samples;
  }
  for (const file of manifest.licenseFiles) {
    if (!/^[a-zA-Z0-9-]+\.txt$/.test(file)) throw new Error(`Invalid license filename: ${file}`);
    const license = fs.readFileSync(path.join(ROOT, 'assets', 'audio', file));
    if (!license.equals(fs.readFileSync(path.join(ROOT, 'macos', 'assets', 'audio', file)))) throw new Error(`Kenney audio license mirror differs: ${file}`);
  }
  const generated = renderModule(presets);
  for (const relative of OUTPUTS) {
    const target = path.join(ROOT, relative);
    if (check) {
      if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== generated) {
        throw new Error(`Generated interaction samples are stale: ${relative}`);
      }
    } else {
      fs.writeFileSync(target, generated, 'utf8');
    }
  }
  return { presets: PUBLIC_PRESETS.length, clips: PUBLIC_PRESETS.length * ROLES.length, modules: OUTPUTS.length, check };
}

if (require.main === module) {
  try {
    const args = process.argv.slice(2);
    if (args.some(arg => arg !== '--check') || args.length > 1) {
      throw new Error('Usage: node scripts/prepare-interaction-audio.cjs [--check]');
    }
    const result = prepareInteractionAudio({ check: args.includes('--check') });
    console.log(`Interaction audio ${result.check ? 'checked' : 'prepared'}: ${result.clips} clips, ${result.modules} matching platform modules.`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}

module.exports = { prepareInteractionAudio, readPcmWav, renderModule, synthesizeOriginalClips };
